constexpr bool verified(const Program &data) {
  for (int c = 0; c < 9; ++c)
    for (int a = 0; a < 9; ++a)
      for (int b = 0; b < 9; ++b) {
        int actual = 0;
        for (const auto &term : data.products)
          actual += term.c[c] * term.a[a] * term.b[b];
        const int expected =
            (a / 3 == c / 3 && b % 3 == c % 3 && a % 3 == b / 3) ? 1 : 0;
        if (actual != expected)
          return false;
      }
  return true;
}
static_assert(verified(program()), "rank-23 integer polynomial identity");
