"""Import pinned dyadic mathematical matrices; independently prove all tensor coefficients."""
import argparse
from fractions import Fraction
import hashlib
import json
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
DATA=ROOT/'third_party/rank48'

def matrix(name,rows,cols):
    manifest=json.loads((DATA/'provenance.json').read_text(encoding='utf-8'))
    payload=(DATA/name).read_bytes()
    if hashlib.sha256(payload).hexdigest()!=manifest['files'][name]['sha256']:
        raise ValueError('coefficient source digest changed')
    lines=payload.decode('ascii').strip().splitlines()
    if lines[0].split()!=[str(rows),str(cols),'R'] or lines[-1].split()!=['0','0','0']:
        raise ValueError('invalid sparse rational matrix envelope')
    result=[[Fraction() for _ in range(cols)] for _ in range(rows)]
    seen=set()
    for line in lines[1:-1]:
        values=line.split()
        if len(values)!=3:raise ValueError('invalid sparse entry')
        row,col=int(values[0])-1,int(values[1])-1
        if not 0<=row<rows or not 0<=col<cols or (row,col) in seen:raise ValueError('invalid/duplicate coordinate')
        value=Fraction(values[2])
        if value.denominator not in (1,2) or abs(value)>2:raise ValueError('unadmitted coefficient')
        result[row][col]=value;seen.add((row,col))
    return result

def verify(left,right,output):
    if len(left)!=48 or len(right)!=48 or len(output)!=16 or any(len(row)!=16 for row in left+right) or any(len(row)!=48 for row in output):
        raise ValueError('rank48 shape mismatch')
    for c in range(16):
        for a in range(16):
            for b in range(16):
                observed=sum((left[t][a]*right[t][b]*output[c][t] for t in range(48)),Fraction())
                expected=int(a//4==c//4 and b%4==c%4 and a%4==b//4)
                if observed!=expected:raise ValueError(f'tensor mismatch: C{c}, A{a}, B{b}')

def load():
    return (matrix('4x4x4_48_204_L.sms',48,16),matrix('4x4x4_48_204_R.sms',48,16),matrix('4x4x4_48_204_P.sms',16,48))

def header(left,right,output):
    digest=hashlib.sha256(json.dumps([[[str(x) for x in row] for row in m] for m in (left,right,output)],separators=(',',':')).encode()).hexdigest()
    lines=['// Generated by tools/rank48_certificate.py from pinned PLinOpt mathematical data.',
           '// CeCILL-B attribution and original matrices: third_party/rank48/.',
           '#pragma once','#include <cstdint>','namespace rns8::detail::rank48 {',
           'struct Term {int8_t a[16],b[16],c[16];};',
           'struct Program {Term products[48];};',
           '// All stored coefficients are twice their exact rational value.',
           'inline constexpr const char* coefficient_sha256="'+digest+'";',
           'constexpr Program program() {return {{']
    for t in range(48):
        fields=[left[t],right[t],[output[c][t] for c in range(16)]]
        if any((x*2).denominator!=1 or abs(x*2)>4 for row in fields for x in row):raise ValueError('coefficient encoding overflow')
        lines.append('  {'+','.join('{'+','.join(str(int(x*2)) for x in row)+'}' for row in fields)+'},')
    lines+=['}};}','// Denominator two is invertible for every admitted odd modulus.',
            'constexpr int coefficient(int twice,uint32_t modulus) {return (twice*int((modulus+1)/2))%int(modulus);}',
            '}','']
    return '\n'.join(lines)

def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--write-header',type=Path)
    args=parser.parse_args();left,right,output=load();verify(left,right,output)
    generated=header(left,right,output)
    if args.write_header:args.write_header.write_text(generated,encoding='utf-8',newline='\n')
    print(json.dumps({'rank':48,'blocks':4,'tensor_coefficients':4096,'exact_rational_tensor':'passed','even_moduli':'classical_control_required','target_qualified':False}))

if __name__=='__main__':main()
